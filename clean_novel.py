def process_file(filepath):
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    original_content = content
    
    # 删除创作系统提示
    for pattern in patterns_to_remove:
        content = re.sub(pattern, '', content, flags=re.MULTILINE)
    
    # 清理多余的空行（超过2个连续空行的改为2个）
    content = re.sub(r'\n{4,}', '\n\n\n', content)
    
    return content

def add_illustration_placeholder(content, chapter_num, desc, prompt):
    """在章节开头添加一个插画占位符"""
    placeholder = f'\n\n<!-- 插画占位符 -->\n<!-- AI绘图提示词：{prompt} -->\n![插画：{desc}](placeholder:chapter-{chapter_num}-cover)\n\n'
    
    # 找到章节标题位置
    pattern = rf'(## 第{chapter_num}章[：:][^\n]*\n)'
    if re.search(pattern, content):
        content = re.sub(pattern, r'\1' + placeholder, content)
    
    return content

